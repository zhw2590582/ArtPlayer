test('candidate: native trigger markup remains a single button and can open the existing popup', async ({ page }) => {
  await setup(page)
  await page.evaluate(() => {
    window.art.controls.update({ name: 'keyboard-selector', html: '<button id="custom-trigger">Choose quality</button>' })
  })
  const button = page.locator('#custom-trigger')
  await expect(button).toHaveAttribute('aria-haspopup', 'listbox')
  expect(await trigger(page).getAttribute('role')).toBeNull()
  await button.focus()
  await page.keyboard.press('Space')
  await expect(item(page, 1)).toBeFocused()
  expect(await page.evaluate(() => window.selectorClicks)).toEqual([[true, true, 'click']])
  expect(await page.evaluate(() => window.art.video.paused)).toBe(true)
  await page.keyboard.press('Escape')
  await expect(button).toBeFocused()
  await expect(list(page)).toBeHidden()
})

test('candidate: a dismissed hovered selector releases the next Escape to fullscreen', async ({ page }) => {
  await setup(page)
  await page.evaluate(() => {
    window.art.fullscreenWeb = true
  })
  await trigger(page).hover()
  await trigger(page).focus()
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Escape')
  await expect(list(page)).toBeHidden()
  expect(await page.evaluate(() => window.art.fullscreenWeb)).toBe(true)
  await page.keyboard.press('Escape')
  await expect.poll(() => page.evaluate(() => window.art.fullscreenWeb)).toBe(false)
})

